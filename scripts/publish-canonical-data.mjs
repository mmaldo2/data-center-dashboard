import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  buildDashboardData,
  stampPublishedMetadata,
  validateCanonicalDataset,
} from "./lib/canonical-data.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const canonicalDir = path.join(rootDir, "data", "canonical");
const derivedDir = path.join(rootDir, "data", "derived");

function serializeNamedExport(name, value) {
  return `export const ${name} = ${JSON.stringify(value, null, 2)};\n`;
}

async function readJson(filePath) {
  return JSON.parse(await readFile(filePath, "utf8"));
}

async function main() {
  const publishedAt = new Date().toISOString();
  const canonical = {
    metadata: stampPublishedMetadata(
      await readJson(path.join(canonicalDir, "metadata.json")),
      publishedAt,
    ),
    companies: await readJson(path.join(canonicalDir, "companies.json")),
    projects: await readJson(path.join(canonicalDir, "projects.json")),
    projectCompanyLinks: await readJson(
      path.join(canonicalDir, "project-company-links.json"),
    ),
    sources: await readJson(path.join(canonicalDir, "sources.json")),
    evidence: await readJson(path.join(canonicalDir, "evidence.json")),
  };

  validateCanonicalDataset(canonical);
  const dashboardData = buildDashboardData(canonical);

  await mkdir(derivedDir, { recursive: true });

  const derivedModule = [
    "// This file is generated by scripts/publish-canonical-data.mjs.",
    "// Do not edit by hand.",
    "",
    serializeNamedExport("DASHBOARD_METADATA", dashboardData.DASHBOARD_METADATA),
    serializeNamedExport("COMPANIES", dashboardData.COMPANIES),
    serializeNamedExport("PROJECTS", dashboardData.PROJECTS),
    serializeNamedExport("SOURCES", dashboardData.SOURCES),
    serializeNamedExport("EVIDENCE", dashboardData.EVIDENCE),
    serializeNamedExport("PROJECT_COMPANY_LINKS", dashboardData.PROJECT_COMPANY_LINKS),
  ].join("\n");

  await writeFile(path.join(derivedDir, "dashboard-data.js"), `${derivedModule}\n`, "utf8");

  console.log(
    `Published canonical data: ${dashboardData.DASHBOARD_METADATA.projectCount} projects, ${dashboardData.DASHBOARD_METADATA.companyCount} companies, ${dashboardData.DASHBOARD_METADATA.evidenceCount} evidence records.`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
